export function getJuice(id) {
  return juices.find((juice) => juice.id === id) || juices[0];
}

export function themeFor(juice) {
  return {
    top: "#FDF7E8",
    bottom: juice.tint,
    ink: "#542C05",
    soft: "#7C5A3A",
    accent: juice.accent,
    card: "rgba(255, 252, 246, 0.9)",
  };
}
